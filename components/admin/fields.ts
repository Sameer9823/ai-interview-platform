const join = (a: string[]) => a.join(", ");
export const companyDefaults = (c: Company) => ({
  name: c.name,
  slug: c.slug,
  website: c.website,
  careersUrl: c.careersUrl,
  logoUrl: c.logoUrl,
  industry: c.industry,
  description: c.description,
  headquarters: c.headquarters,
  hiringInfo: c.hiringInfo,
  roleCategories: join(c.roleCategories),
  prepCategories: join(c.prepCategories),
  origin: c.origin,
  verification: c.verification,
  sourceIds: c.sourceIds,
  moderatorNotes: c.moderatorNotes,
});
export const questionDefaults = (q: Question) => ({
  text: q.text,
  slug: q.slug,
  categorySlug: db().categories.get(q.categoryId)?.slug ?? "",
  type: q.type,
  difficulty: q.difficulty,
  estimatedMinutes: String(q.estimatedMinutes),
  companySlugs: join(q.companyIds.map((i) => db().companies.get(i)?.slug ?? "").filter(Boolean)),
  roles: join(q.roles),
  careerStages: q.careerStages,
  experienceLevels: q.experienceLevels,
  skills: join(q.skills),
  tags: join(q.tagSlugs),
  answerOutline: q.answerOutline,
  explanation: q.explanation,
  exampleAnswer: q.exampleAnswer,
  codeSolution: q.codeSolution,
  codeLanguage: q.codeLanguage,
  testCases: q.testCases.map((t) => `${t.input} => ${t.expected}`).join("\n"),
  hints: q.hints.join("\n"),
  options: q.options.map((o) => `${o.correct ? "*" : ""}${o.text}`).join("\n"),
  origin: q.origin,
  verification: q.verification,
  sourceIds: q.sourceIds,
  moderatorNotes: q.moderatorNotes,
});
